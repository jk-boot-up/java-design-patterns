#!/usr/bin/env bash
#
# Generates the optional narration clips for docs/animation.html.
#
# Output: docs/audio/step-1.m4a ... step-6.m4a
#
# Requirements: macOS (for `say`) and ffmpeg.
#
set -euo pipefail

cd "$(dirname "$0")"

OUT=audio
VOICE="${VOICE:-Samantha}"
RATE="${RATE:-145}"

command -v ffmpeg >/dev/null || { echo "ffmpeg is required"; exit 1; }
command -v say    >/dev/null || { echo "macOS 'say' is required"; exit 1; }

mkdir -p "$OUT"

narrate() {
cat <<'EOF'
Act one. The locator creates lazily. Three finds of a singleton make one. Three finds of a prototype make three. A registry can do neither.
Act two. Configure a fake gateway and the same checkout charges the fake, with no change to it. A genuine step forward.
Act three. The notifier was never configured. The checkout compiled, constructed, and the build was green. In production it charged the customer, then failed.
Act four. Three classes ask the locator. Each is otherwise pure domain logic, now coupled to infrastructure. A unit test must configure it first.
Act five. What is available is not known until run time. ServiceLoader finds the plug-ins. It is this pattern in the standard library.
Act six. Prefer the alternative for business logic. Keep a locator for plug-ins and the composition root. The whole difficulty is the word ask.
EOF
}

i=0
while IFS= read -r line <&3; do
    i=$((i + 1))
    printf '%s' "$line" > "$OUT/.step-$i.txt"
    say -v "$VOICE" -r "$RATE" -o "$OUT/.step-$i.aiff" -f "$OUT/.step-$i.txt"
    ffmpeg -y -loglevel error -i "$OUT/.step-$i.aiff" \
        -c:a aac -b:a 128k -ar 44100 -ac 1 "$OUT/step-$i.m4a"
    rm -f "$OUT/.step-$i.aiff" "$OUT/.step-$i.txt"
    dur=$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$OUT/step-$i.m4a")
    printf 'step-%d.m4a  %5.1fs\n' "$i" "$dur"
done 3< <(narrate)

echo
echo "Wrote $i clips to $OUT/"
