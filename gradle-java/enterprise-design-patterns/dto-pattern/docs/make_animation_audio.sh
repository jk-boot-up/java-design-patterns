#!/usr/bin/env bash
#
# Generates the optional narration clips for docs/animation.html.
#
# Output: docs/audio/step-1.m4a ... step-6.m4a
#
# Requirements: macOS (for `say`) and ffmpeg.
#
set -euo pipefail

cd "$(dirname "$0")"

OUT=audio
VOICE="${VOICE:-Samantha}"
RATE="${RATE:-145}"

command -v ffmpeg >/dev/null || { echo "ffmpeg is required"; exit 1; }
command -v say    >/dev/null || { echo "macOS 'say' is required"; exit 1; }

mkdir -p "$OUT"

narrate() {
cat <<'EOF'
Act one. The serialiser walks every field. The password hash is in it. The lazy order history is loaded, and is in it. Five thousand characters, for a name and a city.
Act two. A developer renames a private field from name to fullName. The client reads the key name, and gets nothing. Nothing failed to compile.
Act three. A DTO is a flat record with exactly the three fields the client needs. Forty-six characters. The history is never loaded.
Act four. The DTO is data, with no behaviour. The domain object enforces a rule and refuses a bad email. The DTO would carry it without complaint.
Act five. Four DTOs carry fifteen fields between them, from a customer with seven. Four mapping methods copy them by hand.
Act six. A record returned from a Spring controller is a DTO. Jackson writes its JSON. It is Backends for Frontends, for one object.
EOF
}

i=0
while IFS= read -r line <&3; do
    i=$((i + 1))
    printf '%s' "$line" > "$OUT/.step-$i.txt"
    say -v "$VOICE" -r "$RATE" -o "$OUT/.step-$i.aiff" -f "$OUT/.step-$i.txt"
    ffmpeg -y -loglevel error -i "$OUT/.step-$i.aiff" \
        -c:a aac -b:a 128k -ar 44100 -ac 1 "$OUT/step-$i.m4a"
    rm -f "$OUT/.step-$i.aiff" "$OUT/.step-$i.txt"
    dur=$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$OUT/step-$i.m4a")
    printf 'step-%d.m4a  %5.1fs\n' "$i" "$dur"
done 3< <(narrate)

echo
echo "Wrote $i clips to $OUT/"
