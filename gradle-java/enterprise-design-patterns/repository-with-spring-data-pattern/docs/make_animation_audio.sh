#!/usr/bin/env bash
#
# Generates the optional narration clips for docs/animation.html.
#
# Output: docs/audio/step-1.m4a ... step-6.m4a
#
# Requirements: macOS (for `say`) and ffmpeg.
#
set -euo pipefail

cd "$(dirname "$0")"

OUT=audio
VOICE="${VOICE:-Samantha}"
RATE="${RATE:-145}"

command -v ffmpeg >/dev/null || { echo "ffmpeg is required"; exit 1; }
command -v say    >/dev/null || { echo "macOS 'say' is required"; exit 1; }

mkdir -p "$OUT"

narrate() {
cat <<'EOF'
Act one. CustomerRepository is an interface, and no class implements it. Spring injects a generated proxy. Save, find and delete all work.
Act two. findDistinctByCityAndOrdersDayGreaterThan gives Ada and Grace, in one statement. The partner's service, unchanged, gives the same answer.
Act three. Every question adds a method. A typo is caught only when Spring reads the name. The compiler cannot check it.
Act four. Counting every customer's orders costs seven statements. An entity graph makes it one, and the interface carries a persistence hint.
Act five. Change a customer from findAll inside a transaction, and it is written with no save. Change it outside, and it is lost with no error.
Act six. This is Repository with the framework supplying the implementation. Swapping the database is claimed far more than used.
EOF
}

i=0
while IFS= read -r line <&3; do
    i=$((i + 1))
    printf '%s' "$line" > "$OUT/.step-$i.txt"
    say -v "$VOICE" -r "$RATE" -o "$OUT/.step-$i.aiff" -f "$OUT/.step-$i.txt"
    ffmpeg -y -loglevel error -i "$OUT/.step-$i.aiff" \
        -c:a aac -b:a 128k -ar 44100 -ac 1 "$OUT/step-$i.m4a"
    rm -f "$OUT/.step-$i.aiff" "$OUT/.step-$i.txt"
    dur=$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$OUT/step-$i.m4a")
    printf 'step-%d.m4a  %5.1fs\n' "$i" "$dur"
done 3< <(narrate)

echo
echo "Wrote $i clips to $OUT/"
